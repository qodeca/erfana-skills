// Builds tokens.css from a DTCG tokens.json with three levels: base, semantic,
// component. Node standard library only.
//
//   node build-tokens.mjs <tokens.json> <tokens.css>           write the CSS
//   node build-tokens.mjs <tokens.json> <tokens.css> --check   fail on drift
//
// Level rules: a base token holds a raw value and no alias; a semantic token
// aliases a base token; a component token aliases a semantic token. Those rules
// are what let a brand change touch one level without breaking the others.
// A semantic token may add theme values under $extensions.design.modes.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { isMain, sameText } from './shared.mjs'

const LEVELS = ['base', 'semantic', 'component']
const ALIAS = /^\{([^{}]+)\}$/
const HEADER = '/* Generated by build-tokens.mjs from tokens.json. Edit tokens.json, not this file. */'

function collect(node, path, level, out, errors) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    if (value === null || typeof value !== 'object') {
      errors.push(`${[level, ...path, key].join('.')}: expected a group or a token`)
    } else if ('$value' in value) {
      out.push({ level, path: [...path, key], token: value })
    } else {
      collect(value, [...path, key], level, out, errors)
    }
  }
}

function cssValue(value, where, errors, type) {
  if (type === 'cubicBezier' && Array.isArray(value)) return `cubic-bezier(${value.join(', ')})`
  if (type === 'shadow' && value && typeof value === 'object' && !Array.isArray(value)) {
    const part = key => cssValue(value[key] ?? 0, where, errors)
    return `${value.inset ? 'inset ' : ''}${part('offsetX')} ${part('offsetY')} ${part('blur')} ${part('spread')} ${value.color}`
  }
  if (typeof value === 'string' || typeof value === 'number') return String(value)
  if (value && typeof value === 'object' && 'value' in value && 'unit' in value) return `${value.value}${value.unit}`
  if (Array.isArray(value)) return value.join(', ')
  errors.push(`${where}: unsupported $value – use a string, a number, or {"value","unit"}`)
  return ''
}

/** Returns { css, errors } for a parsed tokens document. */
export function buildCss(doc) {
  const errors = []
  const tokens = []
  for (const level of LEVELS) {
    if (!doc[level] || typeof doc[level] !== 'object') errors.push(`missing level "${level}"`)
    else collect(doc[level], [], level, tokens, errors)
  }
  for (const key of Object.keys(doc)) {
    if (!key.startsWith('$') && !LEVELS.includes(key)) errors.push(`unknown top-level group "${key}" – use base, semantic, component`)
  }

  const byRef = new Map()
  const byName = new Map()
  for (const t of tokens) {
    t.ref = [t.level, ...t.path].join('.')
    t.name = `--${t.path.join('-')}`
    byRef.set(t.ref, t)
    if (byName.has(t.name)) errors.push(`${t.ref}: name ${t.name} is already used by ${byName.get(t.name).ref}`)
    byName.set(t.name, t)
  }

  const resolve = (t, value, where) => {
    const hit = typeof value === 'string' ? ALIAS.exec(value) : null
    const allowed = { semantic: 'base', component: 'semantic' }[t.level]
    if (!hit) {
      if (t.level !== 'base') errors.push(`${where}: a ${t.level} token must alias a ${allowed} token, not hold a raw value`)
      return cssValue(value, where, errors, t.token.$type)
    }
    const target = byRef.get(hit[1])
    if (t.level === 'base') errors.push(`${where}: a base token holds a raw value, not an alias`)
    else if (!target) errors.push(`${where}: unknown alias ${value}`)
    else if (target.level !== allowed) errors.push(`${where}: a ${t.level} token must alias a ${allowed} token, not ${target.level}`)
    return target ? `var(${target.name})` : ''
  }

  const root = { base: [], semantic: [], component: [] }
  const modes = new Map()
  for (const t of tokens) {
    root[t.level].push(`  ${t.name}: ${resolve(t, t.token.$value, t.ref)};`)
    const extra = t.token.$extensions?.design?.modes ?? {}
    for (const [mode, value] of Object.entries(extra)) {
      if (t.level !== 'semantic') errors.push(`${t.ref}: only semantic tokens may have modes`)
      if (!modes.has(mode)) modes.set(mode, [])
      modes.get(mode).push(`  ${t.name}: ${resolve(t, value, `${t.ref} (${mode})`)};`)
    }
  }

  const blocks = [HEADER, '', ':root {']
  for (const level of ['base', 'semantic']) {
    blocks.push(`  /* ${level} */`, ...root[level])
  }
  // Declared on every theme root too: a var() resolves where it is declared, so
  // a :root-only component token would keep the light value inside a dark frame.
  blocks.push('}', '', ':root,', '[data-theme] {', '  /* component */', ...root.component, '}')
  for (const [mode, lines] of [...modes].sort(([a], [b]) => a.localeCompare(b))) {
    blocks.push('', `[data-theme="${mode}"] {`, ...lines, '}')
  }
  return { css: `${blocks.join('\n')}\n`, errors }
}

function main(argv) {
  const check = argv.includes('--check')
  const [input, output] = argv.filter(a => a !== '--check')
  if (!input || !output) {
    console.error('usage: node build-tokens.mjs <tokens.json> <tokens.css> [--check]')
    return 2
  }
  let doc
  try {
    doc = JSON.parse(readFileSync(input, 'utf8'))
  } catch (error) {
    console.error(`cannot read ${input}: ${error.message}`)
    return 1
  }
  const { css, errors } = buildCss(doc)
  if (errors.length > 0) {
    for (const e of errors) console.error(`${input}: ${e}`)
    return 1
  }
  if (check) {
    if (!existsSync(output) || !sameText(readFileSync(output, 'utf8'), css)) {
      console.error(`${output} differs from ${input} – run build-tokens.mjs`)
      return 1
    }
    console.log(`${output} matches ${input}`)
    return 0
  }
  writeFileSync(output, css)
  console.log(`wrote ${output}`)
  return 0
}

if (isMain(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2))
}
